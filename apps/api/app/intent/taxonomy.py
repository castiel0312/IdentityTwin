"""Intent Profiler taxonomy and stable evidence vocabulary.

These enums are part of the persisted profile contract. Keep values stable;
downstream dashboards and generated API types depend on them.
"""

from enum import Enum


class IntentHypothesis(str, Enum):
    """Advisory session-intent hypotheses supported by available signals."""

    CONTAINMENT_PROBING = "SUSPECTED_CONTAINMENT_PROBING"
    ACCOUNT_TAKEOVER = "SUSPECTED_ACCOUNT_TAKEOVER"
    PAYEE_REDIRECTION = "SUSPECTED_PAYEE_REDIRECTION"
    VELOCITY_ABUSE = "SUSPECTED_VELOCITY_ABUSE"
    ROUTINE_PAYMENT_OPERATION = "ROUTINE_PAYMENT_OPERATION"
    UNKNOWN_INSUFFICIENT_EVIDENCE = "UNKNOWN_INSUFFICIENT_EVIDENCE"


class IntentConfidence(str, Enum):
    """Ordinal confidence band. The profiler never emits a probability."""

    UNKNOWN = "UNKNOWN"
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"


class ConfidenceReason(str, Enum):
    """Why the deterministic classifier selected a confidence band."""

    NO_SUPPORTING_EVIDENCE = "NO_SUPPORTING_EVIDENCE"
    BASELINE_PROVISIONAL = "BASELINE_PROVISIONAL"
    BASELINE_MATURE = "BASELINE_MATURE"
    SINGLE_WEAK_SIGNAL = "SINGLE_WEAK_SIGNAL"
    TWO_INDEPENDENT_SIGNALS = "TWO_INDEPENDENT_SIGNALS"
    THREE_OR_MORE_INDEPENDENT_SIGNALS = "THREE_OR_MORE_INDEPENDENT_SIGNALS"
    HIGH_SPECIFICITY_SEQUENCE = "HIGH_SPECIFICITY_SEQUENCE"
    CANARY_EVIDENCE = "CANARY_EVIDENCE"
    CONTAINMENT_EVIDENCE = "CONTAINMENT_EVIDENCE"
    REPEATED_CONTAINMENT_EVIDENCE = "REPEATED_CONTAINMENT_EVIDENCE"
    STRUCTURED_RISK_STATE_SEQUENCE = "STRUCTURED_RISK_STATE_SEQUENCE"
    ABSENCE_OF_ANOMALY_IS_NOT_PROOF = "ABSENCE_OF_ANOMALY_IS_NOT_PROOF"


class IntentEvidenceSource(str, Enum):
    """Structured source of one evidence reference."""

    SESSION = "session"
    EVENT = "event"
    RISK_STATE = "risk_state"
    TWIN = "twin"
    PAYOUT = "payout"
    CANARY = "canary"
    INCIDENT = "incident"


class IntentSignalCode(str, Enum):
    """Bounded, explainable signal names used by the classifier."""

    EVENT_AUTH = "EVENT_AUTH"
    EVENT_MFA = "EVENT_MFA"
    EVENT_SECURITY_ANOMALY = "EVENT_SECURITY_ANOMALY"
    EVENT_NAVIGATION = "EVENT_NAVIGATION"
    EVENT_HEARTBEAT = "EVENT_HEARTBEAT"
    EVENT_PAYEE_REGISTRATION = "EVENT_PAYEE_REGISTRATION"
    EVENT_PAYOUT = "EVENT_PAYOUT"
    NEW_DEVICE = "NEW_DEVICE"
    NEW_LOCATION = "NEW_LOCATION"
    UNUSUAL_TIME = "UNUSUAL_TIME"
    NEW_PAYEE = "NEW_PAYEE"
    LARGE_PAYOUT = "LARGE_PAYOUT"
    PAYEE_ADD_THEN_PAYOUT = "PAYEE_ADD_THEN_PAYOUT"
    PAYEE_REGISTRATION_VELOCITY = "PAYEE_REGISTRATION_VELOCITY"
    PAYOUT_VELOCITY = "PAYOUT_VELOCITY"
    CANARY_INTERACTION = "CANARY_INTERACTION"
    DECOY_ROUTING = "DECOY_ROUTING"
    BLOCKED_PAYOUT = "BLOCKED_PAYOUT"
    SESSION_REVOKED = "SESSION_REVOKED"
    BASELINE_MATURE = "BASELINE_MATURE"
    BASELINE_PROVISIONAL = "BASELINE_PROVISIONAL"
    NO_EVENTS = "NO_EVENTS"
    UNKNOWN_EVENT_TYPE = "UNKNOWN_EVENT_TYPE"
