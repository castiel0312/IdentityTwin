CREATE SCHEMA IF NOT EXISTS honey AUTHORIZATION identitytwin_user;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'honey_rw') THEN
        EXECUTE 'CREATE ROLE honey_rw LOGIN PASSWORD ''identitytwin_honey_pass'' NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT';
    END IF;
END
$$;

REVOKE ALL PRIVILEGES ON SCHEMA public FROM honey_rw;
REVOKE ALL PRIVILEGES ON ALL TABLES IN SCHEMA public FROM honey_rw;
GRANT USAGE ON SCHEMA honey TO honey_rw;
ALTER DEFAULT PRIVILEGES FOR ROLE identitytwin_user IN SCHEMA honey
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO honey_rw;
ALTER DEFAULT PRIVILEGES FOR ROLE identitytwin_user IN SCHEMA honey
    GRANT USAGE, SELECT ON SEQUENCES TO honey_rw;
ALTER ROLE honey_rw SET search_path = honey;
